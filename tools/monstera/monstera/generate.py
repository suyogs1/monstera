"""Deterministic project generation.

`plan()` computes every output file (path -> bytes, mode, provenance) in memory from the
validated spec, the schema files, the templates and the pinned toolchain profile. `write()`
and `check()` both use the plan, so `--check` compares exactly what `generate` would write.
"""

from __future__ import annotations

import json
import os
import string
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape as xml_escape

from . import GENERATOR_NAME, GENERATOR_VERSION, emit_kotlin, emit_swift
from .jsonio import canonical_bytes, sha256_hex
from .naming import product_name
from .schema import SchemaStore
from .typemodel import build as build_types

PACKAGE_DIR = Path(__file__).resolve().parent
TEMPLATES = PACKAGE_DIR / "templates"
MANIFEST = "MONSTERA-MANIFEST.json"
SPEC_FILE = "monstera.spec.json"
BINARY_SUFFIXES = {".jar"}
EXECUTABLE = {"android/gradlew"}
# Build output that may live inside a generated tree; ignored by --check and never deleted.
BUILD_DIRS = {"build", ".gradle", ".kotlin", ".build", ".swiftpm", "xtool", ".bsp"}
BUILD_FILES = {"local.properties"}


class _AtTemplate(string.Template):
    delimiter = "@@"


@dataclass(frozen=True)
class OutFile:
    path: str      # POSIX, relative to the output root
    data: bytes
    source: str    # provenance: template path, "schema:<files>" or "spec"
    kind: str      # template | static | model | spec | manifest
    mode: int = 0o644


def toolchain() -> dict[str, Any]:
    return json.loads((PACKAGE_DIR / "toolchain.json").read_text(encoding="utf-8"))


def _normalize(data: bytes, crlf: bool) -> bytes:
    text = data.replace(b"\r\n", b"\n")
    return text.replace(b"\n", b"\r\n") if crlf else text


def _render(template: Path, context: dict[str, str]) -> bytes:
    text = _normalize(template.read_bytes(), crlf=False).decode("utf-8")
    return _AtTemplate(text).substitute(context).encode("utf-8")


def _rel(p: Path) -> str:
    return p.relative_to(PACKAGE_DIR).as_posix()


def plan(spec: dict[str, Any], spec_path_label: str, store: SchemaStore) -> list[OutFile]:
    canonical = canonical_bytes(spec)
    sha = sha256_hex(canonical)
    project, game = spec["project"], spec["game"]
    tc = toolchain()
    types = build_types(store)
    product = product_name(project["id"])
    package = project["identifier"]
    schema_source = "schema:" + ",".join(sorted(store.documents))

    header = f"GENERATED by {GENERATOR_NAME} {GENERATOR_VERSION} from {SPEC_FILE} sha256:{sha[:16]} - do not edit"
    ctx: dict[str, str] = {
        "header_plain": header,
        "header_slash": f"// {header}",
        "header_hash": f"# {header}",
        "header_xml": f"<!-- {header} -->",
        "generator": f"{GENERATOR_NAME} {GENERATOR_VERSION}",
        "spec_path": spec_path_label,
        "spec_sha256": sha,
        "project_id": project["id"],
        "display_name": project["displayName"],
        "display_name_xml": xml_escape(project["displayName"], {'"': "&quot;", "'": "&apos;"}),
        "identifier": package,
        "package": package,
        "product": product,
        "version_name": project["version"]["name"],
        "version_code": str(project["version"]["code"]),
        "min_sdk": str(project["platforms"]["android"]["minSdk"]),
        "compile_sdk": str(tc["android"]["compileSdk"]),
        "target_sdk": str(tc["android"]["targetSdk"]),
        "agp": tc["android"]["androidGradlePlugin"],
        "kotlin_compose": tc["android"]["kotlinComposePlugin"],
        "compose_bom": tc["android"]["composeBom"],
        "activity_compose": tc["android"]["activityCompose"],
        "android_orientation": game["orientation"],
        "swift_tools": tc["ios"]["swiftToolsVersion"],
        "ios_target": project["platforms"]["ios"]["deploymentTarget"],
        "ios_orientations": "\n".join(
            f"        <string>{o}</string>" for o in (
                ["UIInterfaceOrientationPortrait"] if game["orientation"] == "portrait"
                else ["UIInterfaceOrientationLandscapeLeft", "UIInterfaceOrientationLandscapeRight"])),
    }
    rows = []
    if "android" in project["targets"]:
        rows.append("| Android | `android/` (Gradle, Kotlin, Compose) | `cd android && ./gradlew assembleDebug` |")
    if "ios" in project["targets"]:
        rows.append("| iOS | `ios/` (SwiftPM + xtool.yml, SwiftUI, SpriteKit) "
                    "| `cd ios && xtool dev build --triple arm64-apple-ios-simulator` |")
    ctx["platform_rows"] = "\n".join(rows)

    files: list[OutFile] = []

    def template(out: str, tmpl: str) -> None:
        path = TEMPLATES / tmpl
        files.append(OutFile(out, _render(path, ctx), _rel(path), "template",
                             0o755 if out in EXECUTABLE else 0o644))

    template("README.md", "README.md.tmpl")

    if "android" in project["targets"]:
        kt_dir = "android/app/src/main/kotlin/" + package.replace(".", "/")
        template("android/settings.gradle.kts", "android/settings.gradle.kts.tmpl")
        template("android/build.gradle.kts", "android/build.gradle.kts.tmpl")
        template("android/gradle.properties", "android/gradle.properties.tmpl")
        template("android/app/build.gradle.kts", "android/app/build.gradle.kts.tmpl")
        template("android/app/src/main/AndroidManifest.xml", "android/app/src/main/AndroidManifest.xml.tmpl")
        template(f"{kt_dir}/MainActivity.kt", "android/app/src/main/kotlin/MainActivity.kt.tmpl")
        static = TEMPLATES / "android" / "static"
        for src in sorted(p for p in static.rglob("*") if p.is_file()):
            rel = "android/" + src.relative_to(static).as_posix()
            data = src.read_bytes() if src.suffix in BINARY_SUFFIXES else _normalize(src.read_bytes(), src.suffix == ".bat")
            files.append(OutFile(rel, data, _rel(src), "static", 0o755 if rel in EXECUTABLE else 0o644))
        files.append(OutFile("android/app/src/main/assets/" + SPEC_FILE, canonical, "spec", "spec"))
        files.append(OutFile(f"{kt_dir}/generated/MonsteraSpec.kt",
                             emit_kotlin.models(types, f"{package}.generated", ctx["header_slash"]).encode(),
                             schema_source, "model"))
        files.append(OutFile(f"{kt_dir}/generated/GeneratedSpec.kt",
                             emit_kotlin.constant(types, spec, sha, f"{package}.generated", SPEC_FILE,
                                                  ctx["header_slash"]).encode(),
                             schema_source + ";spec", "model"))

    if "ios" in project["targets"]:
        src_dir = f"ios/Sources/{product}"
        template("ios/Package.swift", "ios/Package.swift.tmpl")
        template("ios/xtool.yml", "ios/xtool.yml.tmpl")
        template("ios/Info.plist", "ios/Info.plist.tmpl")
        template(f"{src_dir}/{product}App.swift", "ios/Sources/App.swift.tmpl")
        template(f"{src_dir}/ContentView.swift", "ios/Sources/ContentView.swift.tmpl")
        template(f"{src_dir}/SpecScene.swift", "ios/Sources/SpecScene.swift.tmpl")
        template(f"{src_dir}/SpecIntegrity.swift", "ios/Sources/SpecIntegrity.swift.tmpl")
        files.append(OutFile(f"{src_dir}/Resources/{SPEC_FILE}", canonical, "spec", "spec"))
        files.append(OutFile(f"{src_dir}/Generated/MonsteraSpec.swift",
                             emit_swift.models(types, ctx["header_slash"]).encode(), schema_source, "model"))
        files.append(OutFile(f"{src_dir}/Generated/GeneratedSpec.swift",
                             emit_swift.constant(types, spec, sha, SPEC_FILE, ctx["header_slash"]).encode(),
                             schema_source + ";spec", "model"))

    files.sort(key=lambda f: f.path)
    manifest = {
        "generator": {"name": GENERATOR_NAME, "version": GENERATOR_VERSION},
        "spec": {"path": spec_path_label, "sha256": sha},
        "schemas": store.digests(),
        "toolchain": tc,
        "files": [{"path": f.path, "sha256": sha256_hex(f.data), "source": f.source,
                   "kind": f.kind, "mode": oct(f.mode)[2:]} for f in files],
    }
    files.append(OutFile(MANIFEST, canonical_bytes(manifest), "generator", "manifest"))
    return files


# --------------------------------------------------------------------------- disk operations

def _existing(root: Path) -> set[str]:
    found: set[str] = set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in BUILD_DIRS)
        for name in filenames:
            if name not in BUILD_FILES:
                found.add(Path(dirpath, name).relative_to(root).as_posix())
    return found


@dataclass(frozen=True)
class Drift:
    changed: tuple[str, ...]
    missing: tuple[str, ...]
    unexpected: tuple[str, ...]

    @property
    def clean(self) -> bool:
        return not (self.changed or self.missing or self.unexpected)


def check(files: list[OutFile], root: Path) -> Drift:
    present = _existing(root) if root.exists() else set()
    wanted = {f.path: f for f in files}
    changed = sorted(p for p, f in wanted.items() if p in present and (root / p).read_bytes() != f.data)
    missing = sorted(p for p in wanted if p not in present)
    unexpected = sorted(present - set(wanted))
    return Drift(tuple(changed), tuple(missing), tuple(unexpected))


class OutputError(Exception):
    pass


def write(files: list[OutFile], root: Path) -> None:
    if root.exists() and any(root.iterdir()) and not (root / MANIFEST).exists():
        raise OutputError(f"{root} is not empty and has no {MANIFEST}; refusing to overwrite it")
    # Remove every non-build file (previous output), then write the new plan.
    if root.exists():
        for rel in sorted(_existing(root), reverse=True):
            (root / rel).unlink()
        for dirpath, _, _ in os.walk(root, topdown=False):  # deepest first
            d = Path(dirpath)
            inside_build = any(part in BUILD_DIRS for part in d.relative_to(root).parts)
            if d != root and not inside_build and not any(d.iterdir()):
                d.rmdir()
    for f in files:
        target = root / f.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(f.data)
        os.chmod(target, f.mode)
