"""Deterministic project generation.

`plan()` computes every output file (path -> bytes, mode, provenance) in memory from the
validated spec, the schema files, the templates and the pinned toolchain profile. `write()`
and `check()` both use the plan, so `--check` compares exactly what `generate` would write.
"""

from __future__ import annotations

import json
import os
import stat
import string
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any
from xml.sax.saxutils import escape as xml_escape

from . import GENERATOR_NAME, GENERATOR_VERSION, emit_kotlin, emit_swift
from .jsonio import canonical_bytes, sha256_hex
from .naming import product_name
from .schema import SchemaStore
from .typemodel import build as build_types

PACKAGE_DIR = Path(__file__).resolve().parent
TEMPLATES = PACKAGE_DIR / "templates"
MANIFEST = "MONSTERA-MANIFEST.json"
SPEC_FILE = "monstera.spec.json"
BINARY_SUFFIXES = {".jar"}
EXECUTABLE = {"android/gradlew"}
# Build output the platform tools create at FIXED locations inside a generated tree. Only these
# exact paths are ignored by --check/verify and never deleted. A directory named "build" anywhere
# else (e.g. under Sources/, which SwiftPM compiles) is NOT build output and is reported.
BUILD_OUTPUT_DIRS = (
    "android/.gradle", "android/.kotlin", "android/build", "android/app/build",
    "ios/.build", "ios/.swiftpm", "ios/xtool", "ios/.bsp",
)
BUILD_OUTPUT_FILES = ("android/local.properties",)
GUIDANCE_FILE = ".kiro/steering/monstera-generated.md"
LAYOUTS = {"fixture", "app"}


class _AtTemplate(string.Template):
    delimiter = "@@"


@dataclass(frozen=True)
class OutFile:
    path: str      # POSIX, relative to the output root
    data: bytes
    source: str    # provenance: template path, "schema:<files>" or "spec"
    kind: str      # template | static | model | spec | manifest
    mode: int = 0o644


def toolchain() -> dict[str, Any]:
    return json.loads((PACKAGE_DIR / "toolchain.json").read_text(encoding="utf-8"))


def _normalize(data: bytes, crlf: bool) -> bytes:
    text = data.replace(b"\r\n", b"\n")
    return text.replace(b"\n", b"\r\n") if crlf else text


def _render(template: Path, context: dict[str, str]) -> bytes:
    text = _normalize(template.read_bytes(), crlf=False).decode("utf-8")
    return _AtTemplate(text).substitute(context).encode("utf-8")


def _rel(p: Path) -> str:
    return p.relative_to(PACKAGE_DIR).as_posix()


def owned_roots_for(layout: str, targets: list[str]) -> list[str]:
    """Paths (relative to the output root) the generator owns, besides the manifest itself.

    fixture: the whole directory (generated/<id>/, G1 behaviour).
    app:     only the native projects and the single Kiro guidance file (apps/<id>/, G1.5).
             Everything else under apps/<id>/ (spec, assets, README, ...) is hand-maintained.
    """
    if layout == "fixture":
        return ["."]
    if layout == "app":
        # Fixed set, independent of project.targets: dropping a target must not change ownership
        # (review issue 18). An unused root simply has no files.
        return sorted(["android", "ios", GUIDANCE_FILE])
    raise ValueError(f"unknown layout {layout!r}")


def plan(spec: dict[str, Any], spec_path_label: str, store: SchemaStore,
         layout: str = "fixture") -> list[OutFile]:
    if layout not in LAYOUTS:
        raise ValueError(f"unknown layout {layout!r}; expected one of {sorted(LAYOUTS)}")
    canonical = canonical_bytes(spec)
    sha = sha256_hex(canonical)
    project, game = spec["project"], spec["game"]
    tc = toolchain()
    types = build_types(store)
    product = product_name(project["id"])
    package = project["identifier"]
    schema_source = "schema:" + ",".join(sorted(store.documents))

    header = f"GENERATED by {GENERATOR_NAME} {GENERATOR_VERSION} from {SPEC_FILE} sha256:{sha[:16]} - do not edit"
    ctx: dict[str, str] = {
        "header_plain": header,
        "header_slash": f"// {header}",
        "header_hash": f"# {header}",
        "header_xml": f"<!-- {header} -->",
        "generator": f"{GENERATOR_NAME} {GENERATOR_VERSION}",
        "spec_path": spec_path_label,
        "spec_sha256": sha,
        "project_id": project["id"],
        "display_name": project["displayName"],
        "display_name_xml": xml_escape(project["displayName"], {'"': "&quot;", "'": "&apos;"}),
        "identifier": package,
        "package": package,
        "product": product,
        "version_name": project["version"]["name"],
        "version_code": str(project["version"]["code"]),
        "min_sdk": str(project["platforms"]["android"]["minSdk"]),
        "compile_sdk": str(tc["android"]["compileSdk"]),
        "target_sdk": str(tc["android"]["targetSdk"]),
        "agp": tc["android"]["androidGradlePlugin"],
        "kotlin_compose": tc["android"]["kotlinComposePlugin"],
        "compose_bom": tc["android"]["composeBom"],
        "activity_compose": tc["android"]["activityCompose"],
        "android_orientation": game["orientation"],
        "swift_tools": tc["ios"]["swiftToolsVersion"],
        "ios_target": project["platforms"]["ios"]["deploymentTarget"],
        "ios_orientations": "\n".join(
            f"        <string>{o}</string>" for o in (
                ["UIInterfaceOrientationPortrait"] if game["orientation"] == "portrait"
                else ["UIInterfaceOrientationLandscapeLeft", "UIInterfaceOrientationLandscapeRight"])),
    }
    rows = []
    if "android" in project["targets"]:
        rows.append("| Android | `android/` (Gradle, Kotlin, Compose) | `cd android && ./gradlew assembleDebug` |")
    if "ios" in project["targets"]:
        rows.append("| iOS | `ios/` (SwiftPM + xtool.yml, SwiftUI, SpriteKit) "
                    "| `cd ios && xtool dev build --triple arm64-apple-ios-simulator` |")
    ctx["platform_rows"] = "\n".join(rows)

    files: list[OutFile] = []

    def template(out: str, tmpl: str) -> None:
        path = TEMPLATES / tmpl
        files.append(OutFile(out, _render(path, ctx), _rel(path), "template",
                             0o755 if out in EXECUTABLE else 0o644))

    if layout == "fixture":
        template("README.md", "README.md.tmpl")  # in the app layout README.md is hand-maintained
    # One optional, documentation-only Kiro guidance file. No build reads it (decision 1, G1.5).
    template(GUIDANCE_FILE, "kiro-guidance.md.tmpl")

    if "android" in project["targets"]:
        kt_dir = "android/app/src/main/kotlin/" + package.replace(".", "/")
        template("android/settings.gradle.kts", "android/settings.gradle.kts.tmpl")
        template("android/build.gradle.kts", "android/build.gradle.kts.tmpl")
        template("android/gradle.properties", "android/gradle.properties.tmpl")
        template("android/app/build.gradle.kts", "android/app/build.gradle.kts.tmpl")
        template("android/app/src/main/AndroidManifest.xml", "android/app/src/main/AndroidManifest.xml.tmpl")
        template(f"{kt_dir}/MainActivity.kt", "android/app/src/main/kotlin/MainActivity.kt.tmpl")
        static = TEMPLATES / "android" / "static"
        for src in sorted(p for p in static.rglob("*") if p.is_file()):
            rel = "android/" + src.relative_to(static).as_posix()
            data = src.read_bytes() if src.suffix in BINARY_SUFFIXES else _normalize(src.read_bytes(), src.suffix == ".bat")
            files.append(OutFile(rel, data, _rel(src), "static", 0o755 if rel in EXECUTABLE else 0o644))
        files.append(OutFile("android/app/src/main/assets/" + SPEC_FILE, canonical, "spec", "spec"))
        files.append(OutFile(f"{kt_dir}/generated/MonsteraSpec.kt",
                             emit_kotlin.models(types, f"{package}.generated", ctx["header_slash"]).encode(),
                             schema_source, "model"))
        files.append(OutFile(f"{kt_dir}/generated/GeneratedSpec.kt",
                             emit_kotlin.constant(types, spec, sha, f"{package}.generated", SPEC_FILE,
                                                  ctx["header_slash"]).encode(),
                             schema_source + ";spec", "model"))

    if "ios" in project["targets"]:
        src_dir = f"ios/Sources/{product}"
        template("ios/Package.swift", "ios/Package.swift.tmpl")
        template("ios/xtool.yml", "ios/xtool.yml.tmpl")
        template("ios/Info.plist", "ios/Info.plist.tmpl")
        template(f"{src_dir}/{product}App.swift", "ios/Sources/App.swift.tmpl")
        template(f"{src_dir}/ContentView.swift", "ios/Sources/ContentView.swift.tmpl")
        template(f"{src_dir}/SpecScene.swift", "ios/Sources/SpecScene.swift.tmpl")
        template(f"{src_dir}/SpecIntegrity.swift", "ios/Sources/SpecIntegrity.swift.tmpl")
        files.append(OutFile(f"{src_dir}/Resources/{SPEC_FILE}", canonical, "spec", "spec"))
        files.append(OutFile(f"{src_dir}/Generated/MonsteraSpec.swift",
                             emit_swift.models(types, ctx["header_slash"]).encode(), schema_source, "model"))
        files.append(OutFile(f"{src_dir}/Generated/GeneratedSpec.swift",
                             emit_swift.constant(types, spec, sha, SPEC_FILE, ctx["header_slash"]).encode(),
                             schema_source + ";spec", "model"))

    files.sort(key=lambda f: f.path)
    manifest = {
        "generator": {"name": GENERATOR_NAME, "version": GENERATOR_VERSION},
        "spec": {"path": spec_path_label, "projectId": project["id"], "sha256": sha},
        "layout": layout,
        "ownedRoots": owned_roots_for(layout, project["targets"]),
        "schemas": store.digests(),
        "toolchain": tc,
        "files": [{"path": f.path, "sha256": sha256_hex(f.data), "source": f.source,
                   "kind": f.kind, "mode": oct(f.mode)[2:]} for f in files],
    }
    files.append(OutFile(MANIFEST, canonical_bytes(manifest), "generator", "manifest"))
    return files



# --------------------------------------------------------------------------- disk operations

class OutputError(Exception):
    pass


def _is_build_output(rel: str) -> bool:
    return rel in BUILD_OUTPUT_FILES or any(rel == d or rel.startswith(d + "/") for d in BUILD_OUTPUT_DIRS)


def _in_owned(rel: str, owned: list[str]) -> bool:
    return rel == MANIFEST or any(o == "." or rel == o or rel.startswith(o + "/") for o in owned)


_WINDOWS = os.name == "nt"


def _is_link(path: Path) -> bool:
    """True for a symlink, an NTFS junction, or anything else that resolves somewhere other than
    where it sits. Such entries are never followed, written through or deleted through."""
    if path.is_symlink():
        return True
    isjunction = getattr(os.path, "isjunction", None)  # Python 3.12+
    if isjunction is not None and isjunction(path):
        return True
    try:
        here = os.path.normcase(os.path.join(os.path.realpath(path.parent), path.name))
        return os.path.normcase(os.path.realpath(path)) != here
    except OSError:
        return True


def _mode_differs(path: Path, mode: int) -> bool:
    current = path.stat().st_mode
    if _WINDOWS:  # only the read-only attribute is meaningful on Windows
        return bool(current & stat.S_IWRITE) != bool(mode & 0o200)
    return (current & 0o777) != mode


def _scan(root: Path, owned: list[str]) -> tuple[set[str], list[str]]:
    """Non-build-output files inside the owned roots (plus the manifest), and any symlinks met
    on the way (never followed). Files outside the owned roots are invisible: the generator
    can't report, change or delete what it doesn't own."""
    files: set[str] = set()
    links: list[str] = []

    def walk(start: Path) -> None:
        for dirpath, dirnames, filenames in os.walk(start, followlinks=False):
            base = Path(dirpath)
            kept = []
            for d in sorted(dirnames):
                rel = (base / d).relative_to(root).as_posix()
                if _is_link(base / d):
                    links.append(rel)
                elif not _is_build_output(rel):
                    kept.append(d)
            dirnames[:] = kept
            for name in filenames:
                rel = (base / name).relative_to(root).as_posix()
                if _is_link(base / name):
                    links.append(rel)
                elif not _is_build_output(rel):
                    files.add(rel)

    if "." in owned:
        walk(root)
        return files, sorted(links)
    for entry in sorted(set(owned) | {MANIFEST}):
        target = root / entry
        # A symlink anywhere on the way to an owned root would redirect writes outside it.
        for i in range(1, len(Path(entry).parts) + 1):
            hop = root.joinpath(*Path(entry).parts[:i])
            if (hop.exists() or hop.is_symlink()) and _is_link(hop):
                links.append(hop.relative_to(root).as_posix())
                break
        else:
            if target.is_dir():
                walk(target)
            elif target.is_file():
                files.add(entry)
    return files, sorted(set(links))


def _owned_from(manifest: dict[str, Any]) -> list[str]:
    owned = manifest.get("ownedRoots")
    if not (isinstance(owned, list) and owned and all(isinstance(o, str) for o in owned)):
        raise OutputError(f"{MANIFEST} has a missing or invalid ownedRoots value")
    for o in owned:
        if o == ".":
            continue
        posix = PurePosixPath(o)
        # POSIX-relative only: no backslashes, drives, roots ("\\Windows"), "..", or "./x" spellings.
        if (not o or "\\" in o or ":" in o or o.startswith("/") or ".." in posix.parts
                or posix.as_posix() != o):
            raise OutputError(f"{MANIFEST} ownedRoots entry {o!r} escapes the output directory")
    return owned


@dataclass(frozen=True)
class Drift:
    changed: tuple[str, ...]
    missing: tuple[str, ...]
    unexpected: tuple[str, ...]

    @property
    def clean(self) -> bool:
        return not (self.changed or self.missing or self.unexpected)


def _planned_manifest(files: list[OutFile]) -> dict[str, Any]:
    return json.loads(next(f.data for f in files if f.path == MANIFEST))


def check(files: list[OutFile], root: Path) -> Drift:
    """Compare a directory's owned roots with a fresh plan (used by `generate --check`)."""
    owned = _owned_from(_planned_manifest(files))
    present, links = _scan(root, owned) if root.exists() else (set(), [])
    wanted = {f.path: f for f in files}
    changed = sorted(p for p, f in wanted.items()
                     if p in present and ((root / p).read_bytes() != f.data or _mode_differs(root / p, f.mode)))
    missing = sorted(p for p in wanted if p not in present)
    unexpected = sorted((present - set(wanted)) | set(links))
    return Drift(tuple(changed), tuple(missing), tuple(unexpected))


def read_manifest(root: Path) -> dict[str, Any] | None:
    """None if there is no manifest. OutputError if one exists but is not a valid, current
    MONSTERA manifest (callers fail closed on that)."""
    path = root / MANIFEST
    if not path.exists() and not path.is_symlink():
        return None
    if _is_link(path) or not path.is_file():
        raise OutputError(f"{path} is not a regular file")
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise OutputError(f"{path} is not valid JSON: {exc}") from None
    return _validated(manifest, path)


def _validated(manifest: Any, path: Path) -> dict[str, Any]:
    def bad(why: str) -> None:
        raise OutputError(f"{path} is not a valid {MANIFEST}: {why}")

    if not isinstance(manifest, dict):
        bad("not a JSON object")
    generator = manifest.get("generator")
    if not isinstance(generator, dict) or generator.get("name") != GENERATOR_NAME:
        bad("missing or foreign 'generator'")
    if not isinstance(manifest.get("spec"), dict):
        bad("'spec' must be an object")
    # layout and ownedRoots are required: a manifest without them would otherwise be read as
    # whole-directory ownership (review issue 3).
    if manifest.get("layout") not in LAYOUTS:
        bad("missing or unknown 'layout'")
    owned = _owned_from(manifest)
    if owned != owned_roots_for(manifest["layout"], []):
        bad(f"ownedRoots {owned} do not match layout '{manifest['layout']}'")
    files = manifest.get("files")
    if not isinstance(files, list):
        bad("'files' must be a list")
    for entry in files:
        if not (isinstance(entry, dict) and isinstance(entry.get("path"), str)
                and isinstance(entry.get("sha256"), str)
                and isinstance(entry.get("mode", "644"), str) and len(entry.get("mode", "644")) == 3
                and set(entry.get("mode", "644")) <= set("01234567")):
            bad("each file entry needs string 'path', 'sha256' and an octal 'mode'")
        if not _in_owned(entry["path"], owned) or ".." in PurePosixPath(entry["path"]).parts:
            bad(f"file {entry['path']!r} is outside ownedRoots")
    return manifest


def verify(root: Path) -> Drift:
    """Compare a directory with ITS OWN manifest (no regeneration). Detects hand edits,
    deleted files and added files even when the generator or spec has since changed."""
    manifest = read_manifest(root)
    if manifest is None:
        raise OutputError(f"{root} has no valid {MANIFEST}")
    present, links = _scan(root, _owned_from(manifest))
    recorded = {e["path"]: e["sha256"] for e in manifest["files"]}
    modes = {e["path"]: int(e.get("mode", "644"), 8) for e in manifest["files"]}
    changed = sorted(p for p, h in recorded.items()
                     if p in present and (sha256_hex((root / p).read_bytes()) != h or _mode_differs(root / p, modes[p])))
    missing = sorted(p for p in recorded if p not in present)
    unexpected = sorted((present - set(recorded) - {MANIFEST}) | set(links))
    return Drift(tuple(changed), tuple(missing), tuple(unexpected))


def write(files: list[OutFile], root: Path, force: bool = False) -> None:
    """Write a plan without ever silently destroying data.

    Only the plan's owned roots (and the manifest) are ever read, changed or deleted. Files
    outside them (e.g. apps/<id>/monstera.spec.json, assets/, README.md) are never touched.

    Always refused (even with force): owned paths containing files that are neither listed in a
    valid manifest nor byte-identical to this plan; an invalid manifest; a layout or owned-root
    change; links (symlinks, junctions) on or inside owned paths. `--force` only discards edits
    to files the previous manifest lists; it never deletes a file the generator didn't write.
    Refused unless force: another project's output, or a listed file modified since the last run.
    Files are replaced (written to a temporary file, then renamed), never rewritten in place, so a
    hard link from an owned path can't modify the file it links to.
    Build-output locations are never touched.
    The manifest is written last; an interrupted run leaves only files equal to the plan or to the
    previous manifest, so re-running completes it.
    """
    if root.exists() and not root.is_dir():
        raise OutputError(f"{root} exists and is not a directory")
    if (root.exists() or root.is_symlink()) and _is_link(root):
        raise OutputError(f"{root} is a symlink or junction; refusing to write through it")
    planned = {f.path: f.data for f in files}
    new_manifest = json.loads(planned[MANIFEST])
    owned = _owned_from(new_manifest)
    present, links = _scan(root, owned) if root.exists() else (set(), [])
    if links:
        raise OutputError(f"{root} contains links ({', '.join(links)}); refusing to write through them")

    previous = read_manifest(root) if root.exists() else None  # raises if present but invalid
    if previous is None:
        foreign = sorted(p for p in present - {MANIFEST} if planned.get(p) != (root / p).read_bytes())
        if foreign:
            # Not overridable: --force must never wipe an arbitrary directory (e.g. `--out .`).
            # Files identical to the plan are our own output from an interrupted first run.
            raise OutputError(f"{root} has files in generator-owned paths but no {MANIFEST} (not "
                              f"generator-owned): {', '.join(foreign[:10])}; choose an empty or "
                              "generator-owned directory")
    if previous is not None:
        old_layout = previous.get("layout", "fixture")
        if old_layout != new_manifest["layout"] or _owned_from(previous) != owned:
            # Not overridable: widening ownership (e.g. app -> fixture) could claim user files.
            raise OutputError(f"{root} was generated with layout '{old_layout}' and ownedRoots "
                              f"{_owned_from(previous)}; refusing to change them to '{new_manifest['layout']}' "
                              f"{owned}. Use a fresh output directory.")
    problems: list[str] = []   # overridable with force
    unowned: list[str] = []    # never overridable
    if previous is not None and previous["spec"].get("projectId") not in (None, new_manifest["spec"]["projectId"]):
        problems.append(f"{root} belongs to project '{previous['spec']['projectId']}', "
                        f"not '{new_manifest['spec']['projectId']}'")
    recorded = {e["path"]: e["sha256"] for e in (previous or {}).get("files", [])}
    for rel in sorted(present - {MANIFEST}):
        data = (root / rel).read_bytes()
        if planned.get(rel) == data:
            continue  # already the new content (e.g. after an interrupted run)
        if rel not in recorded:
            unowned.append(rel)
        elif recorded[rel] != sha256_hex(data):
            problems.append(f"modified since last generation: {rel}")
    if unowned:
        raise OutputError("refusing to overwrite: not generator-owned (not in the previous manifest):\n  "
                          + "\n  ".join(unowned)
                          + "\nMove or delete these files yourself; --force never removes files the generator "
                            "didn't write.")
    if problems and not force:
        raise OutputError("refusing to overwrite:\n  " + "\n  ".join(problems)
                          + "\nMove your changes into the spec or templates, or re-run with --force to discard them.")

    for rel in sorted(present - set(planned)):
        assert _in_owned(rel, owned) and rel in recorded, rel  # only files the generator wrote
        (root / rel).unlink()
    if root.exists():
        for start in (["."] if "." in owned else [o for o in owned if (root / o).is_dir()]):
            for dirpath, _, _ in os.walk(root / start, topdown=False):  # deepest first; prune empty dirs
                d = Path(dirpath)
                rel = d.relative_to(root).as_posix()
                if d != root and not _is_build_output(rel) and not any(d.iterdir()):
                    d.rmdir()
    for f in sorted(files, key=lambda f: f.path == MANIFEST):  # manifest last
        target = root / f.path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not (target.exists() and target.read_bytes() == f.data):
            _replace(target, f.data)
        os.chmod(target, f.mode)


def _replace(target: Path, data: bytes) -> None:
    """Write via a sibling temporary file and an atomic rename. The old directory entry is replaced,
    so content shared through a hard link is never modified (review issue 2)."""
    temp = target.with_name(f".{target.name}.monstera-tmp")
    try:
        temp.write_bytes(data)
        if target.exists() and not os.access(target, os.W_OK):
            os.chmod(target, stat.S_IWRITE | stat.S_IREAD)  # Windows can't rename over a read-only file
        os.replace(temp, target)
    finally:
        if temp.exists():
            temp.unlink()
