def grid(text: str) -> list[str]:
    rows = [r for r in text.strip("\n").split("\n")]
    if len(rows) != FRAME or any(len(r) != FRAME for r in rows):
        raise SystemExit(f"a frame must be {FRAME}x{FRAME}: {[len(r) for r in rows]}")
    return rows


def png(width: int, height: int, pixels: list[list[tuple[int, int, int, int]]]) -> bytes:
    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in pixels)
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def sheet(palette, frames, columns, rows) -> bytes:
    w, h = columns * FRAME, rows * FRAME
    pixels = [[(0, 0, 0, 0)] * w for _ in range(h)]
    for n, text in enumerate(frames):
        cx, cy = (n % columns) * FRAME, (n // columns) * FRAME
        for y, line in enumerate(grid(text)):
            for x, ch in enumerate(line):
                if ch != ".":
                    if ch not in palette:
                        raise SystemExit(f"colour {ch!r} is not in the palette")
                    pixels[cy + y][cx + x] = palette[ch]
    return png(w, h, pixels)


def main() -> None:
    for game, (palette, frames, columns, rows, sprites) in GAMES.items():
        data = sheet(palette, frames, columns, rows)
        (Path(__file__).parent / f"{game}-atlas.png").write_bytes(data)
        spec_path = REPO / "apps" / game / "monstera.spec.json"
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        spec["game"]["atlas"] = {"png": base64.b64encode(data).decode("ascii"), "frameWidth": FRAME,
                                 "frameHeight": FRAME, "columns": columns, "rows": rows}
        for kind in spec["game"]["runtime"]["kinds"]:
            frames_, tpf = sprites.get(kind["id"], ([], 1))
            kind["sprite"] = {"frames": frames_, "ticksPerFrame": tpf}
        spec_path.write_bytes(canonical_bytes(spec))
        print(f"{game}: {len(data)} bytes PNG, {len(spec['game']['atlas']['png'])} base64 characters")


if __name__ == "__main__":
    main()
