// Authored sprite proof, browser half. One session on the real engine worker and IndexedDB:
//   load the Lantern Run template (no atlas, no sprites) -> fork its identity -> import the fixture sheet (an existing atlas PNG,
//   docs/evidence/atlas-native-proof/source-sheet.png) with provenance -> slice it -> build the atlas -> assign frames to three kinds
//   -> apply -> Generate source files -> Download ZIP.
// The spec inside the downloaded ZIP is the exported canonical spec v5. It must equal the engine's canonical text of the draft.
// The script writes that spec, the ZIP's generated trees check (regenerated by the CLI from it), and a small identity record to
// OUT (default docs/evidence/atlas-native-proof). With --check it writes nothing and fails unless the committed spec is identical.
// Serves dist/ with `vite preview` (run `npm run build` first). Env: SMOKE_CHANNEL (e.g. "chrome").
import { projectActions } from "./project-actions.mjs";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright-core";
import { preview } from "vite";
import { resetStudioStorage } from "./storage.mjs";

const studio = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(studio, "..");
const OUT = process.env.ATLAS_PROOF_OUT ?? join(repo, "docs", "evidence", "atlas-native-proof");
const checkOnly = process.argv.includes("--check");
const SHEET = join(OUT, "source-sheet.png");
const FORK = { id: "atlas-proof", displayName: "Atlas Proof", identifier: "app.monstera.atlasproof" };
// kind -> sprite. Frames index the sheet (8 frames of 16x16): 0 saucer, 2 and 3 bat wings, 4 ember.
const ASSIGN = { keeper: { frames: "0", tpf: 1 }, lantern: { frames: "4", tpf: 1 }, wisp: { frames: "2, 3", tpf: 8 } };

const checks = [];
const check = (name, ok, detail = "") => { checks.push({ name, ok: Boolean(ok) }); console.log(`${ok ? "PASS" : "FAIL"}  ${name}${ok || !detail ? "" : `: ${detail}`}`); };
const sha256 = (b) => createHash("sha256").update(b).digest("hex");
function python(args) {
  for (const [cmd, ...pre] of [["python3"], ["python"], ["py", "-3"]]) {
    const probe = spawnSync(cmd, [...pre, "--version"], { encoding: "utf8" });
    if (probe.error || probe.status !== 0) continue;
    return spawnSync(cmd, [...pre, ...args], { encoding: "utf8", cwd: repo, env: { ...process.env, PYTHONUTF8: "1" } });
  }
  throw new Error("no python interpreter found");
}
const rel0 = (b, f) => f.slice(b.length + 1).replaceAll("\\", "/");
const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));

if (!existsSync(SHEET)) { console.error(`missing fixture sheet ${SHEET}`); process.exit(1); }
const server = await preview({ root: studio, preview: { port: 0, host: "127.0.0.1", open: false } });
const origin = server.resolvedUrls.local[0];
const browser = await chromium.launch(process.env.SMOKE_CHANNEL ? { channel: process.env.SMOKE_CHANNEL } : {});
const work = mkdtempSync(join(tmpdir(), "atlas-proof-"));
let exported = null;
try {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const page = await ctx.newPage();
  const problems = [];
  page.on("pageerror", (e) => problems.push(`pageerror: ${e.message}`));
  page.on("console", (m) => { if (m.type() === "error") problems.push(`console.error: ${m.text()}`); });
  await page.goto(origin, { waitUntil: "load" });
  await resetStudioStorage(page);
  await page.waitForFunction(() => window.ready === true, null, { timeout: 90000 });
  await page.evaluate(() => window.session.loadTemplate("lantern-run"));
  const settled = () => page.waitForFunction(() => { const s = window.session.store.getState(); return s.validation !== null && s.validatedRevision === s.revision; }, null, { timeout: 60000 });
  await settled();
  const go = async (hash) => { await page.evaluate((h) => { window.location.hash = h; }, hash); await page.waitForTimeout(200); };
  const manifests = () => page.evaluate(() => window.session.project.getState().manifests);
  const doc = () => page.evaluate(() => window.session.store.getState().doc);

  const before = await doc();
  check("the template starts with no atlas and no sprites", before.game.atlas.png === "" && before.game.runtime.kinds.every((k) => k.sprite.frames.length === 0));

  // ---- fork identity: recorded goldens are bound to the template's spec, a fork has none
  await go("/designer/overview");
  for (const [path, value] of [["project.id", FORK.id], ["project.displayName", FORK.displayName], ["project.identifier", FORK.identifier]]) {
    await page.fill(`[data-path="$.${path}"]`, value);
    await page.press(`[data-path="$.${path}"]`, "Tab");
  }
  await settled();
  check("the project is a fork with its own identity", (await doc()).project.id === FORK.id && (await doc()).project.identifier === FORK.identifier);

  // An import is refused while an unsaved edit is in flight, so wait until the fork is stored.
  await page.waitForFunction(() => window.session.project.getState().status === "saved", null, { timeout: 30000 });
  // ---- import the fixture sheet with provenance
  await go("/assets/library");
  await page.waitForSelector('[data-testid="asset-library"]', { timeout: 15000 });
  await page.setInputFiles('[data-testid="asset-file"]', { name: "source-sheet.png", mimeType: "image/png", buffer: readFileSync(SHEET) });
  await page.selectOption('[data-testid="asset-origin"]', "user-owned");
  await page.fill('[data-testid="asset-license"]', "proprietary-owned");
  await page.fill('[data-testid="asset-author"]', "MONSTERA project");
  await page.fill('[data-testid="asset-source"]', "apps/pumpkin-blaster/monstera.spec.json game.atlas.png (decoded)");
  await page.click('[data-testid="asset-import-submit"]');
  await page.waitForSelector('[data-testid="asset-row-asset-0001"]', { timeout: 30000 }).catch(async (e) => {
    console.error("import did not finish:", await page.locator('[data-testid="asset-import-error"], [role="alert"]').allTextContents(), await page.textContent('[data-testid="asset-import-submit"]'));
    throw e;
  });
  const asset = (await manifests()).assets.assets[0];
  check("the sheet is in the library with its SHA-256 and provenance", asset.sha256 === sha256(readFileSync(SHEET)) && asset.width === 128 && asset.height === 16 && asset.provenance.license === "proprietary-owned", JSON.stringify(asset));

  // ---- slice: 8 columns x 1 row of 16x16
  await go("/sprites/editor");
  await page.waitForSelector('[data-testid="sheet-editor"]', { timeout: 15000 });
  const setGrid = async (k, v) => { await page.fill(`[data-testid="sheet-new"] [data-testid="grid-${k}"]`, String(v)); await page.press(`[data-testid="sheet-new"] [data-testid="grid-${k}"]`, "Enter"); };
  await setGrid("frameWidth", 16); await setGrid("frameHeight", 16); await setGrid("columns", 8); await setGrid("rows", 1);
  await page.click('[data-testid="sheet-create"]');
  await page.waitForSelector('[data-testid="sheet-row-sheet-1"]', { timeout: 15000 });
  const sheet = (await manifests()).animations.sheets[0];
  check("the sheet is sliced into 8 frames of 16x16", sheet.frames.length === 8 && sheet.frames.every((f) => f.w === 16 && f.h === 16), JSON.stringify(sheet.grid));

  // ---- build the atlas, assign frames, apply
  await page.selectOption('[data-testid="atlas-sheet"]', sheet.id);
  await page.click('[data-testid="atlas-build"]');
  await page.waitForSelector('[data-testid="atlas-info"]', { timeout: 30000 });
  check("the atlas is built in the browser and not yet in the specification", (await doc()).game.atlas.png === "" && /Not applied yet/.test(await page.textContent('[data-testid="atlas-info"]')));
  for (const [kind, a] of Object.entries(ASSIGN)) {
    await page.fill(`[data-testid="atlas-frames-${kind}"]`, a.frames);
    if (a.tpf !== 1) { await page.fill(`[data-testid="atlas-tpf-${kind}"]`, String(a.tpf)); await page.press(`[data-testid="atlas-tpf-${kind}"]`, "Enter"); }
  }
  await page.click('[data-testid="atlas-apply"]');
  await page.waitForFunction(() => window.session.store.getState().doc.game.atlas.png !== "", null, { timeout: 60000 });
  await settled();
  const authored = await doc();
  const errors = await page.locator('[data-testid="atlas-errors"]').count();
  check("apply is accepted by the engine and the oracle hash is unchanged", errors === 0 && /simulation hash is unchanged/.test(await page.textContent('[data-testid="atlas-info"]')));
  const sprites = Object.fromEntries(authored.game.runtime.kinds.map((k) => [k.id, k.sprite]));
  check("the spec carries the assigned sprites", JSON.stringify(sprites) === JSON.stringify({ keeper: { frames: [0], ticksPerFrame: 1 }, lantern: { frames: [4], ticksPerFrame: 1 }, wisp: { frames: [2, 3], ticksPerFrame: 8 } }), JSON.stringify(sprites));
  check("the atlas is 8 x 1 frames of 16x16", ["frameWidth", "frameHeight", "columns", "rows"].every((k) => authored.game.atlas[k] === { frameWidth: 16, frameHeight: 16, columns: 8, rows: 1 }[k]));

  // ---- export: Generate source files -> Download ZIP
  await go("/release/export");
  await page.waitForSelector('[data-testid="export-generate"]', { timeout: 15000 });
  await page.click('[data-testid="export-generate"]');
  await page.waitForSelector('[data-testid="export-tree"]', { timeout: 120000 });
  const [dl] = await Promise.all([page.waitForEvent("download", { timeout: 60000 }), page.click('[data-testid="export-download"]')]);
  const zip = join(work, "export.zip");
  await dl.saveAs(zip);
  const canonicalText = await page.evaluate(() => window.session.store.getState().validation.canonicalText);
  const specSha = await page.evaluate(() => window.session.store.getState().validation.sha256);
  const x = python(["-m", "zipfile", "-e", zip, join(work, "x")]);
  check("the ZIP extracts", x.status === 0, x.stderr);
  const files = walk(join(work, "x"));
  const [specDl] = await projectActions(page, () => Promise.all([page.waitForEvent("download", { timeout: 60000 }), page.click('[data-testid="export-button"]')]));
  const specFile = join(work, "monstera.spec.json");
  await specDl.saveAs(specFile);
  exported = readFileSync(specFile);
  check("the exported spec is the engine's canonical text of the draft (SHA-256 equal)", exported.toString("utf8") === canonicalText && sha256(exported) === specSha, `${sha256(exported)} vs ${specSha}`);
  const gradle = files.find((f) => f.endsWith("android/app/build.gradle.kts") || f.endsWith("android\\app\\build.gradle.kts"));
  check("the ZIP holds both native projects", Boolean(gradle) && files.some((f) => f.endsWith("monstera-atlas.png") && /[\\/]ios[\\/]/.test(f)));
  const root = dirname(dirname(dirname(gradle)));

  // ---- the CLI regenerates both native trees from the exported spec, identical to what the ZIP carried
  const regen = join(work, "regen");
  const g = python(["tools/monstera/monstera.py", "generate", specFile, "--out", regen, "--layout", "fixture"]);
  check("the CLI generates both native projects from the exported spec", g.status === 0, g.stderr || g.stdout);
  const rel = (base, f) => f.slice(base.length + 1).replaceAll("\\", "/");
  const inZip = new Map(walk(root).map((f) => [rel(root, f), sha256(readFileSync(f))]));
  const inRegen = new Map(walk(regen).map((f) => [rel(regen, f), sha256(readFileSync(f))]));
  // The ZIP's manifest is the generator's own: same spec SHA-256 and the same hash for every file it lists (it records the spec path it
  // was given and leaves out the README, which are the only differences).
  const manifestOf = (base) => JSON.parse(readFileSync(join(base, "MONSTERA-MANIFEST.json"), "utf8"));
  const zm = manifestOf(root), rm = manifestOf(regen);
  const regenHash = new Map(rm.files.map((f) => [f.path, f.sha256]));
  check("the ZIP's manifest names the same spec SHA-256 and the same file hashes as the CLI's", zm.spec.sha256 === sha256(exported) && rm.spec.sha256 === zm.spec.sha256 && zm.files.length > 50 && zm.files.every((f) => regenHash.get(f.path) === f.sha256));
  const differing = [...inZip].filter(([p, h]) => p !== "MONSTERA-MANIFEST.json" && inRegen.get(p) !== h).map(([p]) => p);
  const notInZip = [...inRegen.keys()].filter((p) => !inZip.has(p));
  check("every file in the Studio ZIP is byte-identical to the CLI's output for the exported spec", inZip.size > 50 && differing.length === 0, differing.slice(0, 5).join(", "));
  check("the CLI adds only its README to the ZIP's files", JSON.stringify(notInZip.sort()) === JSON.stringify(["README.md"]), notInZip.join(", "));
  const atlasBytes = Buffer.from(JSON.parse(exported).game.atlas.png, "base64");
  const atlasFiles = [...inRegen].filter(([p]) => p.endsWith("monstera-atlas.png"));
  check("both native projects bundle the authored atlas bytes unchanged", atlasFiles.length === 2 && atlasFiles.every(([, h]) => h === sha256(atlasBytes)), JSON.stringify(atlasFiles));
  check("no page errors", problems.length === 0, problems.join(" | "));
} finally {
  await browser.close();
  await server.close();
}

const failed = checks.filter((c) => !c.ok);
if (failed.length > 0 || exported === null) { console.error(`${failed.length} check(s) failed`); process.exit(1); }
const record = { specSha256: sha256(exported), specBytes: exported.length, sourceSheetSha256: sha256(readFileSync(SHEET)), fork: FORK, assign: ASSIGN, atlasSha256: sha256(Buffer.from(JSON.parse(exported).game.atlas.png, "base64")) };
const specPath = join(OUT, "monstera.spec.json");
if (checkOnly) {
  const committed = existsSync(specPath) ? readFileSync(specPath) : null;
  if (committed === null || !committed.equals(exported)) { console.error(`the committed ${specPath} differs from what Studio exports (${record.specSha256})`); process.exit(1); }
  console.log(`OK  committed spec equals the Studio export, sha256 ${record.specSha256}`);
} else {
  mkdirSync(OUT, { recursive: true });
  writeFileSync(specPath, exported);
  writeFileSync(join(OUT, "identity.json"), JSON.stringify(record, null, 2) + "\n");
  console.log(`wrote ${specPath} sha256 ${record.specSha256}`);
}
