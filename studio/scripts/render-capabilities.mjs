// Renders the capability matrix (docs/STUDIO-CAPABILITIES.md) from studio/capabilities.json. The registry is the source;
// the Markdown is generated and a test fails when the committed file differs from this output.
// Usage: node scripts/render-capabilities.mjs --write | --check | (no flag: print)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REGISTRY_PATH = join(here, "..", "capabilities.json");
export const MATRIX_PATH = join(here, "..", "..", "docs", "STUDIO-CAPABILITIES.md");

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const paths = (list) => (list.length ? list.map((p) => `\`${p}\``).join("<br>") : "none");

export function renderMatrix(registry) {
  const out = [];
  out.push("<!-- GENERATED by studio/scripts/render-capabilities.mjs from studio/capabilities.json - do not edit -->");
  out.push("# MONSTERA Studio capability matrix", "");
  out.push("Statuses: `implemented` (works end to end, with a test), `prototype` (bounded subset, limits shown), `mock` (simulated, labelled MOCK), `planned` (designed, not built), `unsupported` (cannot be done here). \"Native output\" says what the capability does in the generated Android and iOS apps. \"Now\" is the verified state at the commit that generated this file; \"Target\" is the state the Studio Foundry milestone aims at. Design: `.kiro/specs/studio-foundry/design.md`.", "");
  out.push("## Modules", "");
  out.push("| Module | Now | Target | Native output | Limits |", "|---|---|---|---|---|");
  for (const m of registry.modules) out.push(`| ${cell(m.title)} | ${m.status} | ${m.targetStatus} | ${m.nativeOutput} | ${cell(m.limits)} |`);
  out.push("");
  const groups = [...registry.modules.map((m) => [m.id, m.title]), ["shared", "Shared foundation"]];
  out.push("## Capabilities", "");
  for (const [id, title] of groups) {
    const caps = registry.capabilities.filter((c) => c.module === id);
    if (caps.length === 0) continue;
    out.push(`### ${cell(title)}`, "");
    out.push("| Capability | Now | Target | Native output | Evidence | Limits | Needs |", "|---|---|---|---|---|---|---|");
    for (const c of caps) out.push(`| ${cell(c.title)} | ${c.status} | ${c.targetStatus} | ${c.nativeOutput} | ${paths(c.evidence)} | ${cell(c.limits)} | ${c.requires ? cell(c.requires) : ""} |`);
    out.push("");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

export function loadRegistry(path = REGISTRY_PATH) {
  return JSON.parse(readFileSync(path, "utf8"));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderMatrix(loadRegistry());
  const mode = process.argv[2];
  if (mode === "--write") { writeFileSync(MATRIX_PATH, text); console.log(`wrote ${MATRIX_PATH}`); }
  else if (mode === "--check") {
    const have = readFileSync(MATRIX_PATH, "utf8").replace(/\r\n/g, "\n");
    if (have !== text) { console.error("docs/STUDIO-CAPABILITIES.md is out of date: run npm run capabilities:render"); process.exit(1); }
    console.log("capability matrix is up to date");
  } else process.stdout.write(text);
}