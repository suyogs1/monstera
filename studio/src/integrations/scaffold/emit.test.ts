import { describe, expect, it } from "vitest";
import fixture from "../../project/manifests/fixtures/integrations.valid.json";
import type { IntegrationsManifest } from "../../project/manifests";
import { SECRET_RULES } from "../secrets";
import { HEADER_TAIL } from "./emit";
import { emitScaffold, canShowAd, FREQUENCY_CASES, FREQUENCY_FINAL, FREQUENCY_RULES, scanScaffoldText, unnegatedClaims } from "./index";

const BUILD = "test-build";
const base = (): IntegrationsManifest => structuredClone(fixture) as IntegrationsManifest;
const goldens = import.meta.glob("./golden/*.txt", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
const lf = (s: string) => s.replace(/\r\n/g, "\n");

describe("scaffold emitters", () => {
  const files = emitScaffold(base(), BUILD);

  it("emits the expected file set in a stable order", () => {
    expect(files.map((f) => f.path)).toEqual([
      "scaffold/SETUP.md",
      "scaffold/android/AdPlacements.kt", "scaffold/android/AdService.kt", "scaffold/android/FirebaseServices.kt", "scaffold/android/MockRewardedAdService.kt",
      "scaffold/ios/AdPlacements.swift", "scaffold/ios/AdService.swift", "scaffold/ios/FirebaseServices.swift", "scaffold/ios/MockRewardedAdService.swift",
    ]);
    expect(emitScaffold(base(), BUILD)).toEqual(files);
  });

  it("matches the golden text", () => {
    for (const f of files) {
      const key = `./golden/${f.path.replace(/\//g, "__")}.txt`;
      expect(lf(goldens[key] ?? "MISSING"), f.path).toBe(f.text);
    }
  });

  it("carries the GENERATED header on every file", () => {
    for (const f of files) expect(f.text.split("\n")[0], f.path).toContain(`GENERATED by MONSTERA Studio ${BUILD} - ${HEADER_TAIL}`);
  });

  it("labels the mock and holds no secret or unnegated claim", () => {
    const get = (p: string) => files.find((f) => f.path === p)!.text;
    const kt = get("scaffold/android/MockRewardedAdService.kt");
    const sw = get("scaffold/ios/MockRewardedAdService.swift");
    expect(kt).toContain("class MockRewardedAdService");
    expect(kt).toContain("const val IS_MOCK: Boolean = true");
    expect(sw).toContain("final class MockRewardedAdService");
    expect(sw).toContain("static let isMock = true");
    for (const t of [kt, sw]) { expect(t).toContain("MOCK"); expect(t).toContain("[MOCK AD]"); }
    for (const f of files) {
      expect(scanScaffoldText(f.text), f.path).toEqual([]);
      for (const r of SECRET_RULES) expect(r.pattern.test(f.text), `${f.path} ${r.rule}`).toBe(false);
    }
    expect(get("scaffold/SETUP.md")).toContain("google-services.json");
  });

  it("refuses an invalid or secret-bearing manifest", () => {
    const m = base();
    m.monetization.placements[0]!.rewardKind = ["AI", "za", "A".repeat(35)].join("");
    expect(() => emitScaffold(m, BUILD)).toThrow(/cannot emit/);
  });

  it("flags unnegated claim words only", () => {
    expect(unnegatedClaims("This is live.")).toHaveLength(1);
    expect(unnegatedClaims("There is no live backend.")).toHaveLength(0);
  });
});

describe("frequency limit", () => {
  it("hand-computed cases", () => {
    // (min, max, shown, last, now)
    expect(canShowAd(120, 3, 0, -1, 0)).toBe(true);     // first show
    expect(canShowAd(120, 3, 1, 100, 219)).toBe(false); // 119 s < 120 s
    expect(canShowAd(120, 3, 1, 100, 220)).toBe(true);  // exactly 120 s
    expect(canShowAd(120, 3, 3, 100, 9999)).toBe(false); // session cap reached
    expect(canShowAd(0, 5, 2, 50, 50)).toBe(true);      // no spacing needed
    expect(canShowAd(0, 0, 0, -1, 0)).toBe(false);      // max 0 means never
  });
  it("the shared table (rendered into the Kotlin and Swift tests) holds", () => {
    for (const [min, max, shown, last, now, expected] of FREQUENCY_CASES) expect(canShowAd(min, max, shown, last, now), [min, max, shown, last, now].join()).toBe(expected);
  });

  it("the rendered rule expressions agree with the TS function on a grid", () => {
    const f = new Function("minSecondsBetween", "maxPerSession", "shownCount", "lastShownSeconds", "nowSeconds",
      `${FREQUENCY_RULES.map((r) => `if (${r.when}) return ${r.result};`).join(" ")} return ${FREQUENCY_FINAL};`) as (...a: number[]) => boolean;
    for (const min of [0, 1, 120]) for (const max of [0, 1, 3]) for (const shown of [0, 1, 3, 4]) for (const last of [-1, 0, 100]) for (const now of [0, 100, 101, 220, 1000])
      expect(f(min, max, shown, last, now), [min, max, shown, last, now].join()).toBe(canShowAd(min, max, shown, last, now));
  });

  it("emitted Kotlin and Swift carry the same rule expressions", () => {
    const files = emitScaffold(base(), BUILD);
    for (const p of ["scaffold/android/AdService.kt", "scaffold/ios/AdService.swift"]) {
      const t = files.find((f) => f.path === p)!.text;
      for (const r of FREQUENCY_RULES) expect(t).toContain(r.when);
      expect(t).toContain(FREQUENCY_FINAL);
    }
  });
});
