const lines = (...l: string[]) => l.join("\n") + "\n";
const header = (build: string, open: string, close = "") => `${open} GENERATED by MONSTERA Studio ${build} - ${HEADER_TAIL}${close}`;
const ktCase = (c: readonly [number, number, number, number, number, boolean]) => `            Case(${c.join(", ")}),`;
const swCase = (c: readonly [number, number, number, number, number, boolean]) => `            (${c.join(", ")}),`;
