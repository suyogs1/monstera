// Native extension files (E2). Pure text. emitExtensions() returns every file Studio writes ONCE into the exported
// project's extensions/ tree: the Firebase interfaces and stubs, the AdMob placement constants, AdService,
// MockRewardedAdService, a visible MOCK rewarded overlay, native tests, and the SwiftPM package. The generated Gradle
// project compiles extensions/android; the generated SwiftPM project links extensions/ios/MonsteraExtensions. Nothing
// here contacts a service, includes an SDK or holds an id or key. Files are write-once (design 7): after the first export
// they belong to the developer and re-export never overwrites them.
