function swiftTest(build: string): string {
  return lines(
    header(build, "//"), "import XCTest", "@testable import MonsteraExtensions", "",
    "final class ScaffoldTests: XCTestCase {",
    "    // The same hand-computed table the TypeScript, Kotlin and Swift tests all use.",
    "    func testFrequencyLimitMatchesTheHandComputedTable() {",
    "        let cases: [(Int, Int, Int, Int, Int, Bool)] = [",
    ...FREQUENCY_CASES.map(swCase),
    "        ]",
    "        for c in cases {",
    "            XCTAssertEqual(FrequencyLimit.canShow(c.0, c.1, c.2, c.3, c.4), c.5, \"\\(c)\")",
    "        }",
    "    }", "",
    "    func testMockServiceIsLabelledAndHonoursTheLimit() {",
    "        var log: [String] = []",
    "        var rewards = 0",
    "        let placement = AdPlacement(id: \"rewarded-test\", type: \"rewarded\", trigger: \"manual\", minSecondsBetween: 120, maxPerSession: 2, rewardKind: \"life\", rewardAmount: 1)",
    "        let service = MockRewardedAdService(placements: [placement], log: { log.append($0) })",
    "        XCTAssertTrue(MockRewardedAdService.isMock)",
    "        XCTAssertTrue(service.isMock)",
    "        // 0 s shows; 119 s is 1 s early; 120 s shows (2 of 2); 10000 s is over the cap.",
    "        let shown = [0, 119, 120, 10000].map { now in service.show(\"rewarded-test\", now) { _, _ in rewards += 1 } }",
    "        XCTAssertEqual(shown, [true, false, true, false])",
    "        XCTAssertEqual(rewards, 2)",
    "        XCTAssertEqual(log.count, 4)",
    "        XCTAssertTrue(log.allSatisfy { $0.hasPrefix(\"[MOCK AD]\") })",
    "        XCTAssertEqual(log.filter { $0.contains(\"skipped by frequency limit\") }.count, 2)",
    "    }", "",
    "    func testOnlyARewardedPlacementGrantsAReward() {",
    "        var rewards = 0",
    "        let placement = AdPlacement(id: \"interstitial-test\", type: \"interstitial\", trigger: \"game-lost\", minSecondsBetween: 0, maxPerSession: 5, rewardKind: \"\", rewardAmount: 0)",
    "        let service = MockRewardedAdService(placements: [placement], log: { _ in })",
    "        let shown = service.show(\"interstitial-test\", 0) { _, _ in rewards += 1 }",
    "        let unknown = service.show(\"unknown\", 0) { _, _ in rewards += 1 }",
    "        XCTAssertTrue(shown)",
    "        XCTAssertFalse(unknown)",
    "        XCTAssertEqual(rewards, 0)",
    "    }",
    "}",
  );
}
