const readme = (build: string, first: string, ...rest: string[]) => lines(header(build, "<!--", " -->"), "", first, "", ...rest);
const IOS_TARGET = /^\d+(\.\d+)?$/;
/**
 * Every write-once extension file for a valid manifest, sorted by path. `iosTarget` is the spec's
 * project.platforms.ios.deploymentTarget. Throws on an invalid manifest, a bad target or a failed scan.
 */
export function emitExtensions(manifest: IntegrationsManifest, build: string, iosTarget: string): ExtensionFile[] {
  if (!IOS_TARGET.test(iosTarget)) throw new Error(`cannot emit extensions: deployment target '${iosTarget}' is not a version`);
  const scaffold = emitScaffold(manifest, build);
  const mapped = scaffold.map((f): ExtensionFile => {
    if (f.path === "scaffold/SETUP.md") return { path: "extensions/SETUP.md", text: f.text };
    const m = /^scaffold\/(android|ios)\/(.+)$/.exec(f.path);
    if (!m) throw new Error(`unexpected scaffold path ${f.path}`);
    return { path: m[1] === "android" ? `${KOTLIN_SCAFFOLD_DIR}/${m[2]}` : `${SWIFT_SOURCES_DIR}/${m[2]}`, text: f.text };
  });
  const files: ExtensionFile[] = [
    ...mapped,
    { path: KOTLIN_EXTENSION_FILE, text: kotlinOverlay(build) },
    { path: KOTLIN_TEST_FILE, text: kotlinTest(build) },
    { path: `${SWIFT_SOURCES_DIR}/MonsteraExtensions.swift`, text: swiftOverlay(build) },
    { path: SWIFT_TEST_FILE, text: swiftTest(build) },
    { path: `${SWIFT_PACKAGE_DIR}/Package.swift`, text: swiftPackage(build, iosTarget) },
    {
      path: "extensions/android/README.md",
      text: readme(build, "These sources are compiled into the Android app by the generated Gradle project (`android/app/build.gradle.kts` adds `src/main/kotlin` and `src/test/kotlin` from here).",
        "- `monstera.extensions.MonsteraExtensions.Overlay()` is drawn above the game. It replaces the generated no-op default and shows the MOCK rewarded ad.",
        "- `monstera.studio.scaffold` holds the Firebase stubs, the placement constants, `AdService` and `MockRewardedAdService`.",
        "- Run the tests with `cd android && ./gradlew testDebugUnitTest`.",
        "- Re-generating `android/` and `ios/` never touches this folder, and Studio never overwrites it after the first export.",
        "- If you delete this folder, the generated no-op default is compiled again. See `../SETUP.md`."),
    },
    {
      path: "extensions/ios/README.md",
      text: readme(build, "`MonsteraExtensions/` is a Swift package that the generated `ios/Package.swift` links into the iOS app when `MonsteraExtensions/Package.swift` exists.",
        "- `MonsteraExtensions.overlay()` is drawn above the game. It replaces the generated no-op default and shows the MOCK rewarded ad.",
        "- The package sits one folder below `extensions/ios` because SwiftPM names a local package after its folder, and `ios` is already the name of the generated package.",
        "- Run the tests with `swift test --package-path extensions/ios/MonsteraExtensions` on a Mac.",
        "- Re-generating `android/` and `ios/` never touches this folder, and Studio never overwrites it after the first export.",
        "- If you delete the package, the generated no-op default is linked again. See `../SETUP.md`."),
    },
  ].sort((a, b) => (a.path < b.path ? -1 : 1));
  for (const f of files) {
    const bad = scanScaffoldText(f.text);
    if (bad.length > 0) throw new Error(`extension scan failed for ${f.path}: ${bad[0]}`);
  }
  return files;
}
export const EXTENSION_MAP_PATH = "studio-pack/scaffold/EXTENSIONS.md";
/** The one Studio-owned scaffold file: rewritten on every export, so it always shows what a fresh export would write into extensions/. */
export function extensionMap(files: readonly ExtensionFile[], build: string): string {
  return lines(
    header(build, "<!--", " -->").replace(HEADER_TAIL, "do not edit"), "",
    "# Native extension map", "",
    "Studio wrote these files into `extensions/` on the first export. After that they are yours: Studio never overwrites them, and re-generating `android/` and `ios/` never touches them.",
    "This list is rewritten on every export and shows what a fresh export would write now.", "",
    ...files.map((f) => `- \`${f.path}\``),
  );
}
