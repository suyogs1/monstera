    "                        dialogOpen = true",
    "                    } else {",
    "                        _ = service.show(placement.id, nowSeconds()) { _, _ in }",
    "                        status = \"MOCK ad: skipped by the frequency limit\"",
    "                    }",
    "                }",
    "                .buttonStyle(.borderedProminent)",
    "                .accessibilityIdentifier(\"mock-rewarded-ad-button\")",
    "            }",
    "            .frame(maxWidth: .infinity, alignment: .leading)",
    "            .padding(12)",
    "            .alert(\"MOCK rewarded ad\", isPresented: $dialogOpen) {",
    "                Button(\"Claim MOCK reward\") {",
    "                    _ = service.show(placement.id, nowSeconds()) { kind, amount in",
