import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import fixture from "../../project/manifests/fixtures/integrations.valid.json";
import type { IntegrationsManifest } from "../../project/manifests";
import { exportPack } from "../../pack/export";
import { classOf } from "../../pack/layout";
import { SECRET_RULES } from "../secrets";
import { FREQUENCY_CASES } from "./frequency";
import { emitExtensions, KOTLIN_EXTENSION_FILE, KOTLIN_TEST_FILE, SWIFT_PACKAGE_DIR, SWIFT_TEST_FILE, SWIFT_TOOLS_VERSION } from "./native";
import { scanScaffoldText } from "./scan";
const BUILD = "test-build";
const IOS = "17.0";
const base = (): IntegrationsManifest => structuredClone(fixture) as IntegrationsManifest;
const files = emitExtensions(base(), BUILD, IOS);
const get = (path: string) => files.find((f) => f.path === path)?.text ?? "MISSING";
const enc = new TextEncoder();
const SCAFFOLD_KT = "extensions/android/src/main/kotlin/monstera/studio/scaffold";
const SCAFFOLD_SW = `${SWIFT_PACKAGE_DIR}/Sources/MonsteraExtensions`;
describe("native extension files (E2)", () => {
  it("emits a stable, sorted file set, all under extensions/ and all write-once", () => {
    expect(files.map((f) => f.path)).toEqual([
      "extensions/SETUP.md",
      `${SCAFFOLD_KT}/AdPlacements.kt`, `${SCAFFOLD_KT}/AdService.kt`, `${SCAFFOLD_KT}/FirebaseServices.kt`, `${SCAFFOLD_KT}/MockRewardedAdService.kt`,
      KOTLIN_EXTENSION_FILE, KOTLIN_TEST_FILE,
      "extensions/android/README.md", "extensions/ios/README.md",
      `${SWIFT_PACKAGE_DIR}/Package.swift`,
      `${SCAFFOLD_SW}/AdPlacements.swift`, `${SCAFFOLD_SW}/AdService.swift`, `${SCAFFOLD_SW}/FirebaseServices.swift`, `${SCAFFOLD_SW}/MockRewardedAdService.swift`, `${SCAFFOLD_SW}/MonsteraExtensions.swift`,
      SWIFT_TEST_FILE,
    ].sort());
    expect(emitExtensions(base(), BUILD, IOS)).toEqual(files);
    for (const f of files) expect(classOf(f.path), f.path).toBe("write-once");
  });
  it("labels the mock in source, log prefix and UI text, and contacts nothing", () => {
    for (const p of [`${SCAFFOLD_KT}/MockRewardedAdService.kt`, `${SCAFFOLD_SW}/MockRewardedAdService.swift`]) {
      expect(get(p)).toContain("MOCK");
      expect(get(p)).toContain("[MOCK AD]");
      expect(get(p)).toMatch(/IS_MOCK: Boolean = true|static let isMock = true/);
    }
    for (const p of [KOTLIN_EXTENSION_FILE, `${SCAFFOLD_SW}/MonsteraExtensions.swift`]) {
      expect(get(p)).toContain("MOCK rewarded ad");
      expect(get(p)).toContain("Claim MOCK reward");
      expect(get(p)).toContain("No ad was requested and no ad network was contacted");
    }
    for (const f of files.filter((x) => !x.path.endsWith(".md"))) {
      expect(f.text, f.path).not.toMatch(/https?:\/\/|URLSession|HttpURLConnection|java\.net|ca-app-pub|com\.google\.(android\.gms|firebase)|import Firebase|GoogleMobileAds/);
    }
  });
  it("carries the header on every file and passes the secret and claim scans", () => {
    for (const f of files) {
      expect(f.text.split("\n").slice(0, 2).join("\n"), f.path).toContain(`GENERATED by MONSTERA Studio ${BUILD}`);
      expect(scanScaffoldText(f.text), f.path).toEqual([]);
      for (const r of SECRET_RULES) expect(r.pattern.test(f.text), `${f.path} ${r.rule}`).toBe(false);
    }
  });
  it("states in the first line of each README that the sources are compiled, and SETUP.md keeps the mock honest", () => {
    expect(get("extensions/android/README.md").split("\n")[2]).toMatch(/^These sources are compiled into the Android app/);
    expect(get("extensions/ios/README.md").split("\n")[2]).toMatch(/^`MonsteraExtensions\/` is a Swift package that the generated/);
    const setup = get("extensions/SETUP.md");
    expect(setup).toContain("google-services.json");
    expect(setup).toContain("no backend and no SDK");
    expect(setup).not.toMatch(/not compiled into the app/);
  });
  it("the Kotlin and Swift test tables are exactly the shared hand-computed table", () => {
    const kt = [...get(KOTLIN_TEST_FILE).matchAll(/^\s+Case\((-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+), (true|false)\),$/gm)].map((m) => m.slice(1).join(","));
    const sw = [...get(SWIFT_TEST_FILE).matchAll(/^\s+\((-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+), (true|false)\),$/gm)].map((m) => m.slice(1).join(","));
    const want = FREQUENCY_CASES.map((c) => c.join(","));
    expect(kt).toEqual(want);
    expect(sw).toEqual(want);
  });
  it("the Swift package uses the pinned tools version and the spec's deployment target", () => {
    const pinned = JSON.parse(readFileSync(join(__dirname, "../../../../tools/monstera/monstera/toolchain.json"), "utf8")) as { ios: { swiftToolsVersion: string } };
    expect(SWIFT_TOOLS_VERSION).toBe(pinned.ios.swiftToolsVersion);
    const pkg = get(`${SWIFT_PACKAGE_DIR}/Package.swift`);
    expect(pkg.split("\n")[0]).toBe(`// swift-tools-version: ${SWIFT_TOOLS_VERSION}`);
    expect(pkg).toContain(`.iOS("${IOS}")`);
    expect(() => emitExtensions(base(), BUILD, "17.0\"), .macOS(")).toThrow(/not a version/);
  });
  it("refuses a manifest that carries a secret-shaped value", () => {
    const m = base();
    m.monetization.placements[0]!.rewardKind = ["AI", "za", "A".repeat(35)].join("");
    expect(() => emitExtensions(m, BUILD, IOS)).toThrow(/cannot emit/);
  });
});
describe("extensions survive re-export (ownership)", () => {
  const toPack = (list: { path: string; text: string }[]) => list.map((f) => ({ path: f.path, data: enc.encode(f.text) }));
  it("a developer's edit to an extension file is kept byte for byte when Studio exports again with changed settings", async () => {
    const first = await exportPack({ files: toPack(files) });
    expect(first.ok).toBe(true);
    if (!first.ok) return;
    const edited = first.entries.map((e) => (e.path === KOTLIN_EXTENSION_FILE ? { path: e.path, data: enc.encode("// my own overlay\n") } : { path: e.path, data: e.data }));
    const changed = base();
    changed.monetization.placements[1]!.maxPerSession = 9;
    const second = await exportPack({ files: toPack(emitExtensions(changed, BUILD, IOS)), existing: edited });
    expect(second.ok).toBe(true);
    if (!second.ok) return;
    const entry = (p: string) => second.entries.find((e) => e.path === p)!;
    expect(new TextDecoder().decode(entry(KOTLIN_EXTENSION_FILE).data)).toBe("// my own overlay\n");
    // Every extension file is kept, including the ones the new settings would have changed.
    expect(new TextDecoder().decode(entry(`${SCAFFOLD_KT}/AdPlacements.kt`).data)).toBe(get(`${SCAFFOLD_KT}/AdPlacements.kt`));
    expect(second.kept.sort()).toEqual(files.map((f) => f.path).sort());
  });
});
// Not a test of Studio: writes the extension files for the native build proof (tools and CI call this with E2_OUT set).
describe.skipIf(!process.env["E2_OUT"])("materialize extensions for the native build", () => {
  it("writes extensions/ into $E2_OUT", () => {
    const out = process.env["E2_OUT"] as string;
    for (const f of emitExtensions(base(), "e2-build", process.env["E2_IOS_TARGET"] ?? IOS)) {
      const target = join(out, ...f.path.split("/"));
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, f.text, { encoding: "utf8" });
    }
  });
});
